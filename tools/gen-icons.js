#!/usr/bin/env node
/* The site's icon set: src/data/icons.json, written from Phosphor's SVG files (the
   @phosphor-icons/core devDependency, pinned) for the names in tools/icons.json. Only path
   data gets through (tools/lib/icons.js parseSvg: a whitelist, no DOM library). Nothing is
   imported from the package at runtime; this script alone reads its files. Generators own
   their output: change this file or tools/icons.json and re-run, never edit src/data/icons.json.
   It also writes src/styles/icons.css: one --icon-<name> mask image per icon (shape only, fill black),
   which the shell links ahead of tokens.css. check-static `icons` fails when either file differs from the
   output of render() / renderCss().
   Usage: node tools/gen-icons.js [--check]
   render() is pure over the map and the installed files: the same inputs give the same bytes. */
"use strict";
const fs = require("fs");
const path = require("path");
const site = require("./lib/site");
const icons = require("./lib/icons");

const ROOT = site.ROOT;
const FILE = path.join(ROOT, "src/data/icons.json");
const MAP = path.join(ROOT, "tools/icons.json");
const CSS_FILE = path.join(ROOT, "src/styles/icons.css");
const STALE = "src/data/icons.json is stale: run node tools/gen-icons.js";
const STALE_CSS = "src/styles/icons.css is stale: run node tools/gen-icons.js";

function pkgDir(map) { return path.join(ROOT, "node_modules", map.package); }

/* the Phosphor file a "<weight>/<name>" is, under the installed package */
function fileOf(map, from) {
  const m = /^(bold|fill)\/([a-z0-9-]+)$/.exec(from);
  if (!m) throw new Error("tools/icons.json: `" + from + "` is not <weight>/<name> with weight bold or fill");
  return path.join(pkgDir(map), "assets", m[1], m[2] + "-" + m[1] + ".svg");
}

function load() { return JSON.parse(fs.readFileSync(MAP, "utf8")); }

function render(map) {
  map = map || load();
  const pkgJson = path.join(pkgDir(map), "package.json");
  if (!fs.existsSync(pkgJson)) throw new Error(map.package + " is not installed; run `npm ci`");
  const meta = JSON.parse(fs.readFileSync(pkgJson, "utf8"));
  if (meta.version !== map.version) throw new Error(map.package + " " + meta.version + " is installed, tools/icons.json says " + map.version);
  const out = { "_": "generated by tools/gen-icons.js from tools/icons.json; never edit", source: map.package + " " + map.version, viewBox: icons.VIEWBOX, icons: {} };
  Object.keys(map.icons).sort().forEach(name => {
    const file = fileOf(map, map.icons[name]);
    if (!fs.existsSync(file)) throw new Error(name + ": " + path.relative(ROOT, file) + " does not exist");
    out.icons[name] = { from: map.icons[name], paths: icons.parseSvg(fs.readFileSync(file, "utf8"), path.relative(ROOT, file)) };
  });
  return JSON.stringify(out, null, 2) + "\n";
}

/* src/styles/icons.css from the text render() gave: a data URI per icon, in the encoding tokens.css uses */
function renderCss(jsonText) {
  const data = JSON.parse(jsonText || render());
  const lines = Object.keys(data.icons).sort().map(name => {
    const svg = "<svg xmlns='http://www.w3.org/2000/svg' viewBox='" + data.viewBox + "'>" +
      data.icons[name].paths.map(d => "<path d='" + d + "' fill='black'/>").join("") + "</svg>";
    const enc = svg.replace(/</g, "%3C").replace(/>/g, "%3E").replace(/#/g, "%23");
    return "  --icon-" + name + ': url("data:image/svg+xml,' + enc + '");';
  });
  return "/* generated by tools/gen-icons.js; never edit. Mask images, one per icon of tools/icons.json: the\n" +
    "   shape comes from here, the colour from the background-color of the element that masks with it. */\n" +
    ":root {\n" + lines.join("\n") + "\n}\n";
}

function firstDiff(have, text) {
  const a = (have || "").split("\n"), b = text.split("\n");
  let i = 0; while (i < a.length && i < b.length && a[i] === b[i]) i++;
  return i + 1;
}

function main() {
  const text = render(), css = renderCss(text);
  if (process.argv.includes("--check")) {
    let bad = false;
    [[FILE, text, STALE], [CSS_FILE, css, STALE_CSS]].forEach(([f, want, msg]) => {
      const have = fs.existsSync(f) ? fs.readFileSync(f, "utf8") : null;
      if (have !== want) { console.error(msg + " (first difference at line " + firstDiff(have, want) + ")"); bad = true; }
    });
    if (bad) process.exit(1);
    console.log("src/data/icons.json and src/styles/icons.css are current");
    return;
  }
  fs.writeFileSync(FILE, text);
  fs.writeFileSync(CSS_FILE, css);
  console.log("wrote src/data/icons.json and src/styles/icons.css");
}

if (require.main === module) main();
module.exports = { render, renderCss, load, fileOf, STALE, STALE_CSS, FILE, CSS_FILE, MAP };
