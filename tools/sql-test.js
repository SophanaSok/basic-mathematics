#!/usr/bin/env node
"use strict";
/* Runs the SQL of the event log against a throwaway Postgres in Docker.

   Usage: node tools/sql-test.js [--keep] [--verbose]   (npm run test:sql)
   --keep     leave the container running afterwards (its port is printed)
   --verbose  print every pgTAP line, not only the ones that are not "ok"

   Needs Docker; it is not part of `npm run check` or `check:all` for that reason. It starts the
   supabase/postgres image (the roles anon, authenticated and service_role, the auth schema
   with auth.users and auth.uid(), and pgtap), and stops if one of those is missing instead of
   making a stand-in. Then, in one database and in this order:
     1. supabase/schema.sql as it is on main (git show origin/main:..., else main): the baseline
        the live project has, which a new migration must stand on. This card's own edit of
        schema.sql is deliberately not what is applied here.
     2. every file of supabase/migrations/ that is not on that ref, in order, each twice
        (migrations are idempotent, rule 2 of supabase/migrations/README.md).
     3. supabase/tests/prune_cases.sql (generated by tools/gen-prune-sql-cases.js)
     4. supabase/tests/events.test.sql (pgTAP)
   Exits 1 on a failed statement, a "not ok", or a plan that is not what ran. The container is
   always removed, also on Ctrl-C. */

const fs = require("fs");
const path = require("path");
const { spawn, execFileSync } = require("child_process");

const ROOT = path.join(__dirname, "..");
/* the newest 17.x tag of supabase/postgres on Docker Hub (2026-10-15) and its manifest digest;
   moving either is a deliberate edit, so the suite runs on the same server every time */
const IMAGE_TAG = "17.11.0.004";
const IMAGE_DIGEST = "sha256:6058a6759ab9268cff8ee70641d61f1bd75953316281b76427cf5a6b4db2eafc";
const IMAGE = "supabase/postgres@" + IMAGE_DIGEST;
const NAME = "bm-sql-test";
const args = process.argv.slice(2);
const KEEP = args.includes("--keep"), VERBOSE = args.includes("--verbose");

function run(cmd, argv, input) {
  return new Promise((resolve) => {
    const p = spawn(cmd, argv, { cwd: ROOT, stdio: ["pipe", "pipe", "pipe"] });
    let out = "", err = "";
    p.stdout.on("data", (d) => { out += d; });
    p.stderr.on("data", (d) => { err += d; });
    p.on("error", (e) => resolve({ status: 127, out, err: err + String(e) }));
    p.on("close", (status) => resolve({ status, out, err }));
    p.stdin.on("error", () => {});
    p.stdin.end(input === undefined ? "" : input);
  });
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const docker = (...a) => run("docker", a);
const PSQL = ["exec", "-i", NAME, "psql", "-U", "postgres", "-d", "postgres", "-X", "-q", "-t", "-A", "-v", "ON_ERROR_STOP=1"];
const psql = (sql) => run("docker", PSQL, sql);

let cleaned = false;
async function cleanup() {
  if (cleaned || KEEP) return;
  cleaned = true;
  await docker("rm", "-f", NAME);
}
function fail(msg) { console.error("sql-test: " + msg); process.exitCode = 1; }
/* psql's stderr without the NOTICE lines idempotent statements print */
const errors = (s) => s.split("\n").filter((l) => l && !/^(NOTICE|psql:.*NOTICE):/.test(l) && !/^DETAIL: +drop cascades/.test(l)).join("\n");

function baseline() {
  for (const ref of ["origin/main", "main"]) {
    try { return { ref, sql: execFileSync("git", ["show", ref + ":supabase/schema.sql"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 1 << 26 }) }; } catch (e) { /* try the next */ }
  }
  throw new Error("neither origin/main nor main has supabase/schema.sql; fetch main first");
}
function migrationsAfter() {
  /* the migrations the baseline schema does not yet include: those not on the base ref */
  const dir = path.join(ROOT, "supabase", "migrations");
  const all = fs.readdirSync(dir).filter((f) => /^\d{14}_.*\.sql$/.test(f)).sort();
  let onBase = [];
  for (const ref of ["origin/main", "main"]) {
    try { onBase = execFileSync("git", ["ls-tree", "--name-only", ref, "supabase/migrations/"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).split("\n").map((p) => path.basename(p)); break; } catch (e) { /* next */ }
  }
  return all.filter((f) => !onBase.includes(f));
}

async function main() {
  const t0 = Date.now();
  const base = baseline();
  const migrations = migrationsAfter();
  if (!migrations.length) { fail("no migration newer than " + base.ref + " to test"); return; }

  if ((await docker("image", "inspect", IMAGE)).status !== 0) {
    console.log("pulling supabase/postgres:" + IMAGE_TAG + " (" + IMAGE_DIGEST.slice(0, 19) + "...)");
    const pull = await docker("pull", IMAGE);
    if (pull.status !== 0) { fail("docker pull failed:\n" + pull.err); return; }
  }
  await docker("rm", "-f", NAME);
  const started = await docker("run", "-d", "--rm", "--name", NAME, "-e", "POSTGRES_PASSWORD=postgres", "-p", "127.0.0.1:0:5432", IMAGE);
  if (started.status !== 0) { fail("docker run failed:\n" + started.err); return; }
  process.on("SIGINT", async () => { await cleanup(); process.exit(130); });
  process.on("SIGTERM", async () => { await cleanup(); process.exit(143); });

  /* the image runs its init scripts, restarts, and only then holds the roles */
  let ready = false;
  for (let i = 0; i < 60 && !ready; i++) {
    const r = await psql("select count(*) = 3 from pg_roles where rolname in ('anon', 'authenticated', 'service_role');");
    if (r.status === 0 && r.out.trim() === "t") { await sleep(1500); ready = (await psql("select 1;")).status === 0; } else await sleep(1000);
  }
  if (!ready) { fail("the database was not ready, with its roles, within 60 s"); return; }

  /* the four facts the suite stands on: stop, never stub */
  const facts = await psql(
    "select 'roles ' || count(*) from pg_roles where rolname in ('anon', 'authenticated', 'service_role');\n" +
    "select 'auth.users ' || (to_regclass('auth.users') is not null);\n" +
    "select 'auth.uid ' || (to_regprocedure('auth.uid()') is not null);\n" +
    "create extension if not exists pgtap;\n" +
    "select 'pgtap ' || (select count(*) from pg_extension where extname = 'pgtap');\n");
  const want = ["roles 3", "auth.users true", "auth.uid true", "pgtap 1"];
  if (facts.status !== 0 || want.some((w) => !facts.out.includes(w))) {
    fail("the image does not have what the suite needs (" + want.join(", ") + "):\n" + facts.out + errors(facts.err) + "\nnot stubbing it; pick another image.");
    return;
  }

  const steps = [["schema.sql as on " + base.ref, base.sql]];
  migrations.forEach((m) => {
    const sql = fs.readFileSync(path.join(ROOT, "supabase", "migrations", m), "utf8");
    steps.push([m, sql], [m + " again", sql]);
  });
  steps.push(["prune_cases.sql", fs.readFileSync(path.join(ROOT, "supabase", "tests", "prune_cases.sql"), "utf8")]);
  for (const [label, sql] of steps) {
    const r = await psql(sql);
    if (r.status !== 0) { fail(label + " failed:\n" + errors(r.err) + r.out); return; }
    console.log("applied " + label);
  }

  const t = await psql(fs.readFileSync(path.join(ROOT, "supabase", "tests", "events.test.sql"), "utf8"));
  const lines = t.out.split("\n");
  const bad = lines.filter((l) => /^not ok/.test(l));
  const okCount = lines.filter((l) => /^ok \d+/.test(l)).length;
  const plan = lines.map((l) => /^1\.\.(\d+)$/.exec(l)).find(Boolean);
  lines.forEach((l) => { if (VERBOSE || !/^ok \d+/.test(l)) { if (l) console.log(l); } });
  if (t.status !== 0) { fail("events.test.sql failed:\n" + errors(t.err)); return; }
  if (!plan) { fail("the suite printed no plan"); return; }
  if (bad.length) { fail(bad.length + " test(s) not ok"); return; }
  if (okCount !== Number(plan[1]) || lines.some((l) => /^# Looks like/.test(l))) { fail("plan mismatch: planned " + plan[1] + ", ran " + okCount); return; }
  console.log("pgTAP: " + okCount + " tests, all ok; the migration applied twice without error (" + ((Date.now() - t0) / 1000).toFixed(1) + " s, supabase/postgres:" + IMAGE_TAG + ")");
  if (KEEP) {
    const port = (await docker("port", NAME, "5432")).out.trim();
    console.log("left running as " + NAME + " (" + port + ", user postgres, password postgres); stop it with: docker rm -f " + NAME);
  }
}

main().catch((e) => fail(String(e && e.stack || e))).finally(async () => { await cleanup(); });
